import { api } from './api.js';

// Builds the "key=value&key=value" plaintext strings the bank expects, then
// hands them to the backend's own /test/checksum and /test/encrypt
// endpoints - the actual SHA-512 and AES-256 logic always runs server-side,
// this file just assembles field order and orchestrates the calls.

let cachedConstants = null;

/**
 * Reads the bank's real configured constants (mercode, bank id, currency,
 * language id, user type, app type) from the backend's own
 * GET /test/sample-payment-payload endpoint, by parsing its
 * plainTextBeforeChecksum field. Nothing is hardcoded here - if the
 * backend's application.yml changes, this picks it up automatically.
 */
export async function getBankConstants() {
  if (cachedConstants) return cachedConstants;
  const sample = await api.getSamplePayload();
  const params = {};
  sample.plainTextBeforeChecksum.split('&').forEach((pair) => {
    const idx = pair.indexOf('=');
    params[pair.slice(0, idx)] = pair.slice(idx + 1);
  });
  cachedConstants = {
    mercode: sample.mercode,
    bankId: params.BankId,
    currency: params.CRN,
    langId: params.USER_LANG_ID,
    userType: params.UserType,
    appType: params.AppType,
  };
  return cachedConstants;
}

/** Order matches ParamCodec usage in PaymentService - must stay in this exact order for the checksum to verify. */
function buildOrderedString(pairs) {
  return pairs.map(([k, v]) => `${k}=${v}`).join('&');
}

/**
 * Generates a merchant-side order reference (PRN). In the real integration
 * this is generated by BillDesk/the merchant the instant the customer
 * clicks Pay - the bank never generates it (it only auto-generates its own
 * BID, in PaymentService.generateBid()). This mirrors that exactly.
 */
export function generatePrn() {
  const rand = Math.floor(100 + Math.random() * 900);
  return `BLDK${Date.now()}${rand}`;
}

/**
 * Builds the full encrypted payment request payload for
 * POST /Corporate/prelogin/payment-gateway.
 */
export async function buildPaymentPayload({ prn, amount, merchantName, returnUrl }) {
  const c = await getBankConstants();
  const plain = buildOrderedString([
    ['Action.ShoppingMall.Login.Init', 'Y'],
    ['BankId', c.bankId],
    ['MD', 'P'],
    ['PID', c.mercode],
    ['ITC', merchantName],
    ['PRN', prn],
    ['AMT', amount],
    ['CRN', c.currency],
    ['RU', returnUrl],
    ['CG', 'Y'],
    ['USER_LANG_ID', c.langId],
    ['UserType', c.userType],
    ['AppType', c.appType],
  ]);

  const { checksum } = await api.checksum(plain);
  const fullPlainText = `${plain}&CHECKSUM=${checksum}`;
  const { encrypted } = await api.encrypt(fullPlainText);

  return { mercode: c.mercode, encDhanBankData: encrypted, plainText: fullPlainText };
}

